# Columns each data table must have (copied from the design sheet)
COLUMNS = {
    "products": ["product_id", "product_name", "category", "brand", "price", "description", "is_active",
                 "owner_user_id"],
    "customers": ["customer_id", "name", "email"],
    "sales": ["sale_id", "product_id", "customer_id", "sale_date", "quantity", "unit_price"],
    "return_reasons": ["return_reason_id", "reason_name", "description"],
    "returns": ["return_id", "sale_id", "return_reason_id", "return_date", "returned_quantity",
                "return_status", "refund_amount"],
    "customer_feedback": ["feedback_id", "sale_id", "return_id", "rating", "feedback_text", "feedback_date"],
    "investigations": ["investigation_id", "product_id", "user_id", "query", "started_at",
                       "completed_at", "status"],
    "investigation_findings": ["finding_id", "investigation_id", "finding_type", "finding_text", "confidence"],
    "finding_evidence": ["evidence_id", "finding_id", "source_type", "source_id"],
    "recommendations": ["recommendation_id", "investigation_id", "recommendation_text", "priority",
                        "status", "owner_user_id"],
}
# Parents first, children after (also the order of insertion)
LOAD_ORDER = list(COLUMNS)

# Every table in the design (used to check that existing tables match it)
ALL_COLUMNS = {
    "roles": ["role_id", "role_name"],
    "users": ["user_id", "name", "email", "password_hash", "role_id"],
    "chat_conversations": ["conversation_id", "user_id", "title", "created_at", "updated_at"],
    "chat_messages": ["message_id", "conversation_id", "role", "content", "created_at", "ref", "model", "duration_ms"],
    **COLUMNS,
    "knowledge_documents": ["document_id", "document_name", "source", "document_type", "uploaded_at"],
    "knowledge_chunks": ["chunk_id", "document_id", "chunk_text", "chunk_index", "embedding_reference"],
}


# ------------------------------------------------------------------ CSV -> tables
def _int(series):
    return series.astype("Int64")          # whole numbers that may be empty (NULL)


def _date(series):
    return pd.to_datetime(series).dt.date


def build_tables(raw: pd.DataFrame, now: datetime) -> dict:
    """Split the flat CSV into one DataFrame per table, using the design's column names."""
    t = {}

    t["products"] = (raw.drop_duplicates("product_id")
        .rename(columns={"unit_price": "price"})
        [["product_id", "product_name", "category", "brand", "price"]]
        .assign(description=None, is_active=True))
    # owners are set afterwards with:  python -m scripts.assign_product_owners
    t["products"]["owner_user_id"] = pd.array([pd.NA] * len(t["products"]), dtype="Int64")

    t["customers"] = (raw.drop_duplicates("customer_id")
        .rename(columns={"customer_name": "name", "customer_email": "email"})
        [["customer_id", "name", "email"]])

    t["sales"] = (raw.rename(columns={"quantity_sold": "quantity"})
        .assign(sale_date=lambda d: _date(d["sale_date"]))
        [["sale_id", "product_id", "customer_id", "sale_date", "quantity", "unit_price"]])

    # return_reasons: one row per distinct reason (most common reason gets id 1)
    reason_names = raw["return_reason"].dropna().value_counts().index.tolist()
    reasons = pd.DataFrame({"return_reason_id": range(1, len(reason_names) + 1),
                            "reason_name": reason_names, "description": None})
    t["return_reasons"] = reasons
    reason_id = dict(zip(reasons["reason_name"], reasons["return_reason_id"]))

    rets = raw.dropna(subset=["return_id"]).copy()
    rets["return_reason_id"] = rets["return_reason"].map(reason_id)
    rets["return_date"] = _date(rets["return_date"])
    for c in ["return_id", "return_reason_id", "returned_quantity"]:
        rets[c] = _int(rets[c])
    t["returns"] = rets[["return_id", "sale_id", "return_reason_id", "return_date",
                         "returned_quantity", "return_status", "refund_amount"]]

    fb = raw.dropna(subset=["feedback_id"]).copy()          # no CSV row has both a return and feedback,
    fb["return_id"] = _int(fb["return_id"])                 # so return_id stays empty here (it is optional)
    fb["feedback_id"] = _int(fb["feedback_id"])
    fb["rating"] = _int(fb["feedback_rating"])
    fb["feedback_date"] = _date(fb["feedback_date"])
    t["customer_feedback"] = fb[["feedback_id", "sale_id", "return_id", "rating", "feedback_text", "feedback_date"]]

    inv = raw.dropna(subset=["investigation_id"]).drop_duplicates("investigation_id").copy()
    inv["investigation_id"] = _int(inv["investigation_id"])
    inv["user_id"] = pd.array([pd.NA] * len(inv), dtype="Int64")   # users are created by the app
    inv["query"] = "Why does " + inv["product_name"] + " have a high return rate?"   # assumed text
    inv["started_at"] = now                                                          # assumed
    inv["completed_at"] = now                                                        # assumed
    inv["status"] = inv["investigation_status"]
    t["investigations"] = inv[["investigation_id", "product_id", "user_id", "query",
                               "started_at", "completed_at", "status"]]

    fnd = raw.dropna(subset=["finding_id"]).copy()
    for c in ["finding_id", "investigation_id"]:
        fnd[c] = _int(fnd[c])
    fnd["finding_type"] = "Possible Cause"                                           # assumed
    fnd = fnd.rename(columns={"finding_summary": "finding_text", "finding_confidence": "confidence"})
    t["investigation_findings"] = fnd[["finding_id", "investigation_id", "finding_type",
                                       "finding_text", "confidence"]]

    # The design only allows: return / sale / feedback / knowledge_chunk
    source_map = {"customer_feedback": "feedback"}
    ev = fnd.copy()
    ev["evidence_id"] = range(1, len(ev) + 1)
    ev["source_type"] = ev["evidence_source_type"].replace(source_map)
    ev["source_id"] = _int(ev["evidence_source_id"])
    t["finding_evidence"] = ev[["evidence_id", "finding_id", "source_type", "source_id"]]

    rec = raw.dropna(subset=["recommendation_id"]).copy()
    for c in ["recommendation_id", "investigation_id"]:
        rec[c] = _int(rec[c])
    rec["priority"] = "Medium"                                                       # design default
    rec["owner_user_id"] = pd.array([pd.NA] * len(rec), dtype="Int64")
    rec = rec.rename(columns={"recommendation_status": "status"})
    t["recommendations"] = rec[["recommendation_id", "investigation_id", "recommendation_text",
                                "priority", "status", "owner_user_id"]]
    return t


# ------------------------------------------------------------------ database work
def find_mismatches(engine) -> list[str]:
    """Compare the tables that already exist with the approved design."""
    insp = inspect(engine)
    existing = set(insp.get_table_names())
    problems = []
    for name, cols in ALL_COLUMNS.items():
        if name in existing:
            have = {c["name"] for c in insp.get_columns(name)}
            missing = [c for c in cols if c not in have]
            if missing:
                problems.append(f"  table '{name}' is missing column(s): {', '.join(missing)}")
    return problems


def main():
    reset = "--reset" in sys.argv
    engine = create_engine(settings.database_url)
    raw = pd.read_csv(CSV_PATH)
    print(f"Read {len(raw)} rows from {CSV_PATH}")
    tables = build_tables(raw, datetime.now().replace(microsecond=0))

    # 1. make sure the existing tables match the approved design (BEFORE changing anything)
    if reset:
        print("RESET: deleting the 16 application tables and rebuilding them from the approved design...")
        with engine.begin() as conn:
            for name in reversed(list(DDL)):              # children first
                conn.execute(text(f'DROP TABLE IF EXISTS "{name}" CASCADE'))
    else:
        problems = find_mismatches(engine)
        if problems:
            print("\nYour existing tables do not match the approved design:")
            print("\n".join(problems))
            print("\nNothing was changed. Your tables were probably created by the generated code")
            print("with different column names. Since this is only dummy data, the quickest fix is:")
            print("    python -m scripts.load_data --reset")
            print("(this deletes the 16 application tables and rebuilds them exactly like the design).")
            return

    # 2. create any table that does not exist yet (existing, matching tables are left alone)
    existing = set(inspect(engine).get_table_names())
    with engine.begin() as conn:
        for name, ddl in DDL.items():
            if name not in existing:
                conn.execute(text(ddl))
                print(f"  created table: {name}")

    # 3. empty the data tables, then load them (parents first)
    with engine.begin() as conn:
        names = ", ".join(f'"{n}"' for n in LOAD_ORDER)
        conn.execute(text(f"TRUNCATE TABLE {names} RESTART IDENTITY CASCADE"))
        print("Inserting:")
        for name in LOAD_ORDER:
            df = tables[name]
            df.to_sql(name, conn, if_exists="append", index=False)
            print(f"  {name:<24} {len(df):>4} rows")

        # keep the auto-numbering in sync, so new rows created by the app get fresh ids
        for name in LOAD_ORDER:
            pk = COLUMNS[name][0]
            conn.execute(text(
                f"SELECT setval(pg_get_serial_sequence('{name}', '{pk}'), "
                f"COALESCE((SELECT MAX({pk}) FROM \"{name}\"), 1))"))

    # 4. sanity check
    with engine.connect() as conn:
        print("\nReturn rate per product (returned units / units sold):")
        rows = conn.execute(text("""
            SELECT p.product_id, p.product_name,
                   COALESCE(r.units, 0) AS returned, s.units AS sold
            FROM products p
            JOIN (SELECT product_id, SUM(quantity) AS units FROM sales GROUP BY product_id) s
                 ON s.product_id = p.product_id
            LEFT JOIN (SELECT sa.product_id, SUM(rt.returned_quantity) AS units
                       FROM "returns" rt JOIN sales sa ON sa.sale_id = rt.sale_id
                       GROUP BY sa.product_id) r ON r.product_id = p.product_id
            ORDER BY p.product_id"""))
        for pid, name, ret, sold in rows:
            print(f"  {pid}  {name:<22} {ret:>3} / {sold:<3} = {ret / sold:.0%}")


if __name__ == "__main__":
    main()