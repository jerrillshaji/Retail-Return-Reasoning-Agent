"""
Load the dummy CSV into Postgres, following the approved database design
(Retail_Return_Reasoning_Agent_Database_Design_Revised.xlsx).

The CSV is ONE big flat file. This script splits it into the design's tables:
  products, customers, sales, return_reasons, returns, customer_feedback,
  investigations, investigation_findings, finding_evidence, recommendations

What it does NOT touch: roles, users (your app creates these) and the
knowledge_documents / knowledge_chunks tables (the RAG step fills those later).

Run from the project root:
    python -m scripts.load_data            normal run: checks your tables, then reloads the data
    python -m scripts.load_data --reset    DELETES all 16 application tables and rebuilds them from the
                                           approved design (use when the existing tables do not match)
Safe to run again: a normal run clears ONLY the 10 data tables above and reloads them.
"""

